// Shorthand lookup for brain/glossary. Zero LLM.
//
//   node server/brain-glossary.js "A-day"
//   node server/brain-glossary.js --search calc
//   node server/brain-glossary.js add --term "A-day" --gloss "..." --aliases "A day" --see orgs/eastside-prep
//   node server/brain-glossary.js --check
//   node server/brain-glossary.js --write-index

import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { BRAIN_ROOT, parseFrontmatter, serializeFrontmatter, slugify } from "./brain-lib.js";

export const GLOSS_MAX = 400;
export const SEARCH_CAP = 15;

const INDEX_NAME = "index.md";

function pacificDateKey(now = new Date()) {
  return new Intl.DateTimeFormat("en-CA", {
    timeZone: "America/Los_Angeles",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).format(now);
}

export function glossaryDir(root = BRAIN_ROOT) {
  return path.join(root, "glossary");
}

export function normalizeGlossaryKey(value) {
  return String(value || "")
    .toLowerCase()
    .replace(/['’]/g, "")
    .replace(/[-_./]+/g, " ")
    .replace(/[^a-z0-9\s]+/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

function compactKey(value) {
  return normalizeGlossaryKey(value).replace(/ /g, "");
}

function keysFor(entry) {
  const keys = new Set();
  for (const raw of [entry.slug, entry.term, ...(entry.aliases || [])]) {
    const spaced = normalizeGlossaryKey(raw);
    const compact = compactKey(raw);
    if (spaced) keys.add(spaced);
    if (compact) keys.add(`c:${compact}`);
  }
  return keys;
}

function queryKeys(query) {
  const spaced = normalizeGlossaryKey(query);
  const compact = compactKey(query);
  const keys = new Set();
  if (spaced) keys.add(spaced);
  if (compact) keys.add(`c:${compact}`);
  return keys;
}

function firstSentence(body) {
  const text = String(body || "").replace(/\s+/g, " ").trim();
  const match = text.match(/^.*?[.!?](?=\s|$)/);
  return (match ? match[0] : text).trim();
}

function cleanGloss(gloss) {
  return String(gloss || "").replace(/\s+/g, " ").trim();
}

function splitList(value) {
  return String(value || "")
    .split(",")
    .map((part) => part.trim())
    .filter(Boolean);
}

function uniqueStrings(values) {
  const out = [];
  const seen = new Set();
  for (const value of values) {
    const text = String(value || "").trim();
    if (!text) continue;
    const key = normalizeGlossaryKey(text);
    if (!key || seen.has(key)) continue;
    seen.add(key);
    out.push(text);
  }
  return out;
}

export function entryLine(entry) {
  let line = `- \`${entry.slug}\` — ${entry.term}`;
  if (entry.aliases?.length) line += ` — aliases: ${entry.aliases.join(", ")}`;
  const sentence = firstSentence(entry.body);
  if (sentence) line += ` — ${sentence}`;
  return line;
}

export function buildGlossaryIndex(entries) {
  const lines = [
    "# Glossary",
    "",
    "GENERATED by server/brain-glossary.js. Do not hand-edit.",
    "",
    "Yan-only. Look up one term: node server/brain-glossary.js \"<term>\".",
    "Browse: node server/brain-glossary.js --search \"<stem>\".",
    "Do not glob this folder. Do not read this whole file into a chat turn.",
    "",
  ];
  const sorted = [...entries].sort((a, b) => a.slug.localeCompare(b.slug));
  for (const entry of sorted) lines.push(entryLine(entry));
  if (sorted.length) lines.push("");
  return lines.join("\n");
}

function loadEntry(filePath, problems) {
  const slug = path.basename(filePath, ".md");
  let parsed;
  try {
    parsed = parseFrontmatter(fs.readFileSync(filePath, "utf8"));
  } catch (err) {
    problems.push(`${slug}: ${err instanceof Error ? err.message : err}`);
    return null;
  }
  if (!parsed.fields) {
    problems.push(`${slug}: no frontmatter`);
    return null;
  }
  const fields = parsed.fields;
  const term = typeof fields.term === "string" ? fields.term.trim() : "";
  const aliases = Array.isArray(fields.aliases) ? fields.aliases.map((item) => String(item).trim()).filter(Boolean) : [];
  const see = Array.isArray(fields.see) ? fields.see.map((item) => String(item).trim()).filter(Boolean) : [];
  const body = String(parsed.body || "").trim();
  if (!term) problems.push(`${slug}: missing term`);
  if (fields.kind !== "glossary") problems.push(`${slug}: kind must be glossary`);
  if (!Array.isArray(fields.aliases)) problems.push(`${slug}: aliases must be a JSON array`);
  if (!Array.isArray(fields.see)) problems.push(`${slug}: see must be a JSON array`);
  if (!/^\d{4}-\d{2}-\d{2}$/.test(String(fields.last_touched || ""))) {
    problems.push(`${slug}: last_touched must be YYYY-MM-DD`);
  }
  if (term && `${slugify(term)}.md` !== path.basename(filePath)) {
    problems.push(`${slug}: filename must be ${slugify(term)}.md`);
  }
  if (!body) problems.push(`${slug}: empty gloss`);
  if (body.length > GLOSS_MAX) problems.push(`${slug}: gloss over ${GLOSS_MAX} characters`);
  if (body.includes("<!-- timeline -->")) problems.push(`${slug}: no timeline`);
  if (/\n\s*\n/.test(body)) problems.push(`${slug}: gloss must be one paragraph`);
  if (!term) return null;
  return {
    slug,
    filePath,
    term,
    aliases,
    see,
    lastTouched: String(fields.last_touched || ""),
    body,
  };
}

export function listGlossary(root = BRAIN_ROOT) {
  const dir = glossaryDir(root);
  const entries = [];
  const problems = [];
  if (!fs.existsSync(dir)) return { entries, problems, dir };
  for (const name of fs.readdirSync(dir).sort((a, b) => a.localeCompare(b))) {
    if (!name.endsWith(".md") || name === INDEX_NAME) continue;
    if (name.startsWith(".")) continue;
    const entry = loadEntry(path.join(dir, name), problems);
    if (entry) entries.push(entry);
  }
  const owners = new Map();
  for (const entry of entries) {
    for (const key of keysFor(entry)) {
      if (!owners.has(key)) owners.set(key, []);
      owners.get(key).push(entry.slug);
    }
  }
  const reported = new Set();
  for (const [key, slugs] of owners) {
    const unique = [...new Set(slugs)].sort();
    if (unique.length < 2) continue;
    const id = unique.join(",");
    if (reported.has(id)) continue;
    reported.add(id);
    problems.push(`alias collision ${key.replace(/^c:/, "")}: ${unique.join(", ")}`);
  }
  return { entries, problems, dir };
}

function indexPath(root) {
  return path.join(glossaryDir(root), INDEX_NAME);
}

export function writeGlossaryIndex(root = BRAIN_ROOT) {
  const { entries, dir } = listGlossary(root);
  fs.mkdirSync(dir, { recursive: true });
  const text = buildGlossaryIndex(entries);
  fs.writeFileSync(indexPath(root), text);
  return { count: entries.length, text };
}

export function checkGlossary(root = BRAIN_ROOT) {
  const { entries, problems } = listGlossary(root);
  const expected = buildGlossaryIndex(entries);
  const file = indexPath(root);
  if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== expected) {
    problems.push("stale: glossary/index.md");
  }
  return { ok: problems.length === 0, problems };
}

function findMatches(entries, needles) {
  const wanted = new Set();
  for (const needle of needles) {
    for (const key of queryKeys(needle)) wanted.add(key);
  }
  return entries.filter((entry) => {
    for (const key of keysFor(entry)) {
      if (wanted.has(key)) return true;
    }
    return false;
  });
}

function formatEntry(entry) {
  const lines = [`# ${entry.term} (glossary/${entry.slug})`, ""];
  if (entry.aliases.length) lines.push(`- aliases: ${entry.aliases.join(", ")}`);
  if (entry.see.length) lines.push(`- see: ${entry.see.join(", ")}`);
  lines.push(`- last_touched: ${entry.lastTouched}`, "", entry.body);
  return lines.join("\n");
}

function writeEntry(entry, today) {
  const aliases = uniqueStrings(entry.aliases).filter(
    (alias) => normalizeGlossaryKey(alias) !== normalizeGlossaryKey(entry.term),
  );
  const fields = {
    term: entry.term,
    kind: "glossary",
    aliases,
    see: uniqueStrings(entry.see),
    last_touched: today,
  };
  const text = `${serializeFrontmatter(fields)}${entry.body.trim()}\n`;
  fs.writeFileSync(entry.filePath, text);
}

export function addGlossary({
  root = BRAIN_ROOT,
  term,
  gloss,
  aliases = [],
  see = [],
  today = pacificDateKey(),
} = {}) {
  const cleanTerm = String(term || "").trim();
  const body = cleanGloss(gloss);
  if (!cleanTerm) {
    const error = new Error("missing --term");
    error.code = "usage";
    throw error;
  }
  if (!body) {
    const error = new Error("missing --gloss");
    error.code = "usage";
    throw error;
  }
  if (body.length > GLOSS_MAX) {
    const error = new Error(`gloss over ${GLOSS_MAX} characters`);
    error.code = "invalid";
    throw error;
  }
  if (body.includes("<!-- timeline -->")) {
    const error = new Error("gloss cannot include a timeline");
    error.code = "invalid";
    throw error;
  }
  const slug = slugify(cleanTerm);
  if (!slug) {
    const error = new Error("term has no slug");
    error.code = "invalid";
    throw error;
  }

  const dir = glossaryDir(root);
  fs.mkdirSync(dir, { recursive: true });
  const { entries } = listGlossary(root);
  const matches = findMatches(entries, [cleanTerm, ...aliases]);
  const filePath = path.join(dir, `${slug}.md`);
  if (fs.existsSync(filePath) && !matches.some((entry) => entry.filePath === filePath)) {
    const onDisk = entries.find((entry) => entry.filePath === filePath);
    if (onDisk) matches.push(onDisk);
  }
  const uniqueMatches = [...new Map(matches.map((entry) => [entry.slug, entry])).values()];
  if (uniqueMatches.length > 1) {
    const error = new Error(
      `alias collision: ${uniqueMatches.map((entry) => entry.slug).join(", ")}`,
    );
    error.code = "collision";
    throw error;
  }

  const existing = uniqueMatches[0];
  const next = existing
    ? {
        ...existing,
        aliases: [...existing.aliases, ...aliases, cleanTerm],
        see: [...existing.see, ...see],
        body,
      }
    : {
        slug,
        filePath,
        term: cleanTerm,
        aliases,
        see,
        body,
      };
  if (!existing) next.filePath = filePath;
  writeEntry(next, today);
  writeGlossaryIndex(root);
  return { slug: existing ? existing.slug : slug, created: !existing };
}

export function lookupGlossary(root, query) {
  const { entries } = listGlossary(root);
  return findMatches(entries, [query]);
}

export function searchGlossary(root, query) {
  const { entries } = listGlossary(root);
  const spaced = normalizeGlossaryKey(query);
  const compact = compactKey(query);
  const raw = String(query || "").toLowerCase();
  const hits = entries.filter((entry) => {
    if (spaced && [...keysFor(entry)].some((key) => key.replace(/^c:/, "").includes(spaced))) return true;
    if (compact && compactKey(`${entry.term} ${entry.aliases.join(" ")} ${entry.slug}`).includes(compact)) {
      return true;
    }
    return entryLine(entry).toLowerCase().includes(raw);
  });
  hits.sort((a, b) => a.slug.localeCompare(b.slug));
  return { total: hits.length, shown: hits.slice(0, SEARCH_CAP) };
}

function parseArgs(argv) {
  const out = {
    command: "",
    query: "",
    search: "",
    term: "",
    gloss: "",
    aliases: [],
    see: [],
    check: false,
    writeIndex: false,
  };
  const args = [...argv];
  if (args[0] === "add") {
    out.command = "add";
    args.shift();
  }
  for (let i = 0; i < args.length; i += 1) {
    const arg = args[i];
    if (arg === "--check") out.check = true;
    else if (arg === "--write-index") out.writeIndex = true;
    else if (arg === "--search") {
      out.command = "search";
      out.search = args[i + 1] || "";
      i += 1;
    } else if (arg === "--term") {
      out.term = args[i + 1] || "";
      i += 1;
    } else if (arg === "--gloss") {
      out.gloss = args[i + 1] || "";
      i += 1;
    } else if (arg === "--aliases") {
      out.aliases.push(...splitList(args[i + 1] || ""));
      i += 1;
    } else if (arg === "--see") {
      out.see.push(...splitList(args[i + 1] || ""));
      i += 1;
    } else if (!arg.startsWith("--") && !out.query) {
      out.query = arg;
    }
  }
  if (!out.command && out.query) out.command = "lookup";
  return out;
}

function usageText() {
  return [
    'usage: node server/brain-glossary.js "<term>"',
    '       node server/brain-glossary.js --search "<stem>"',
    '       node server/brain-glossary.js add --term "..." --gloss "..." [--aliases "a, b"] [--see "orgs/slug"]',
    "       node server/brain-glossary.js --check",
    "       node server/brain-glossary.js --write-index",
    "",
  ].join("\n");
}

export function runGlossary(argv, root = BRAIN_ROOT) {
  const args = parseArgs(argv);
  let stdout = "";
  let stderr = "";
  let exitCode = 0;

  try {
    if (args.check) {
      const { ok, problems } = checkGlossary(root);
      if (!ok) {
        stderr = `${problems.join("\n")}\n`;
        exitCode = 1;
      }
    } else if (args.writeIndex) {
      const { count } = writeGlossaryIndex(root);
      stdout = `wrote glossary/index.md (${count} terms)\n`;
    } else if (args.command === "add") {
      const result = addGlossary({
        root,
        term: args.term,
        gloss: args.gloss,
        aliases: args.aliases,
        see: args.see,
      });
      stdout = `${result.created ? "added" : "updated"} glossary/${result.slug}\n`;
    } else if (args.command === "search") {
      if (!args.search.trim()) {
        stderr = "missing --search\n";
        exitCode = 2;
      } else {
        const { total, shown } = searchGlossary(root, args.search);
        if (!total) {
          stderr = "not in glossary\n";
          exitCode = 1;
        } else {
          const lines = [];
          if (total > shown.length) lines.push(`showing ${shown.length} of ${total}`);
          for (const entry of shown) lines.push(entryLine(entry));
          stdout = `${lines.join("\n")}\n`;
        }
      }
    } else if (args.command === "lookup") {
      const matches = lookupGlossary(root, args.query);
      if (!matches.length) {
        stderr = "not in glossary\n";
        exitCode = 1;
      } else if (matches.length === 1) {
        stdout = `${formatEntry(matches[0])}\n`;
      } else {
        const lines = matches.map((entry) => entryLine(entry));
        lines.push("", "multiple matches. Open one:");
        for (const entry of matches) lines.push(`node server/brain-glossary.js ${entry.slug}`);
        stdout = `${lines.join("\n")}\n`;
      }
    } else {
      stderr = usageText();
      exitCode = 2;
    }
  } catch (err) {
    stderr = `${err instanceof Error ? err.message : err}\n`;
    exitCode = err && err.code === "usage" ? 2 : 1;
  }

  return { exitCode, stdout, stderr };
}

const isMain = (() => {
  const arg = process.argv[1];
  if (!arg) return false;
  try {
    return pathToFileURL(arg).href === import.meta.url;
  } catch {
    return false;
  }
})();

if (isMain) {
  const result = runGlossary(process.argv.slice(2));
  if (result.stdout) process.stdout.write(result.stdout);
  if (result.stderr) process.stderr.write(result.stderr);
  process.exitCode = result.exitCode;
}
