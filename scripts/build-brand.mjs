#!/usr/bin/env node
/**
 * Copy brand/palette.mjs into every file that needs literal brand colors.
 *
 *   npm run brand            write the generated blocks
 *   npm run brand -- --check exit 1 if any generated block is stale
 *
 * CSS files get the text between `/* brand:start *\/` and `/* brand:end *\/`.
 * The object-html skill gets its --accent / --ok lines inside
 * `<!-- brand:<name> -->` ... `<!-- brand:end -->`.
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import palette from "../brand/palette.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CHECK = process.argv.includes("--check");

const CSS_TARGETS = [
  { file: "education/styles.css", brands: ["personal", "agent", "jype", "debate"] },
  { file: "2026-27-electives/styles.css", brands: ["personal"] },
  { file: "prasham-schedule-options/styles.css", brands: ["personal"] },
];
const SWIFT_FILE = "ios/YanLevin/YanLevin/Design/BrandPalette.generated.swift";
const SKILL_FILE = ".cursor/skills/object-html/SKILL.md";
const SKILL_REGIONS = { "object-html-personal": "personal", "object-html-jype": "jype" };

const HEX = /^#[0-9a-f]{6}$/;

function kebab(name) {
  return name.replace(/([a-z])([A-Z0-9])/g, "$1-$2").toLowerCase();
}

function rgbTriple(hex) {
  const n = parseInt(hex.slice(1), 16);
  return `${(n >> 16) & 255}, ${(n >> 8) & 255}, ${n & 255}`;
}

function cssTokens(brand) {
  return Object.entries(palette[brand]).filter(([key]) => key !== "ios");
}

for (const brand of Object.keys(palette)) {
  for (const [key, value] of cssTokens(brand)) {
    for (const mode of ["light", "dark"]) {
      const v = value[mode];
      if (typeof v !== "string") throw new Error(`${brand}.${key}.${mode} must be a string`);
      if (v.startsWith("#") && !HEX.test(v)) {
        throw new Error(`${brand}.${key}.${mode} must be lowercase #rrggbb, got ${v}`);
      }
    }
  }
}

function cssDecls(brands, mode, indent) {
  const lines = [];
  for (const brand of brands) {
    for (const [key, value] of cssTokens(brand)) {
      const name = `--yl-${brand}-${kebab(key)}`;
      const v = value[mode];
      lines.push(`${indent}${name}: ${v};`);
      if (HEX.test(v)) lines.push(`${indent}${name}-rgb: ${rgbTriple(v)};`);
    }
    if (mode === "light" && palette[brand].accent) {
      lines.push(`${indent}--yl-${brand}-accent-light-rgb: ${rgbTriple(palette[brand].accent.light)};`);
    }
  }
  return lines.join("\n");
}

function cssBlock(brands) {
  return [
    "/* brand:start. Generated by `npm run brand` from brand/palette.mjs. Do not edit by hand. */",
    ":root {",
    cssDecls(brands, "light", "  "),
    "}",
    "@media (prefers-color-scheme: dark) {",
    '  :root:not([data-resolved-theme="light"]) {',
    cssDecls(brands, "dark", "    "),
    "  }",
    "}",
    'html[data-resolved-theme="dark"] {',
    cssDecls(brands, "dark", "  "),
    "}",
    "/* brand:end */",
  ].join("\n");
}

function swiftColor(hex) {
  const h = hex.slice(1).toUpperCase();
  return `Color(red: 0x${h.slice(0, 2)} / 255, green: 0x${h.slice(2, 4)} / 255, blue: 0x${h.slice(4, 6)} / 255)`;
}

function swiftName(brand, key, mode) {
  const cap = (s) => s[0].toUpperCase() + s.slice(1);
  return `${brand}${cap(key)}${cap(mode)}`;
}

function swiftFile() {
  const out = [
    "// Generated by `npm run brand` from brand/palette.mjs. Do not edit by hand.",
    "import SwiftUI",
    "",
    "enum BrandPalette {",
  ];
  for (const brand of Object.keys(palette)) {
    const ios = palette[brand].ios || {};
    out.push(`    // ${brand}`);
    for (const [key, value] of cssTokens(brand)) {
      for (const mode of ["light", "dark"]) {
        const override = ios[`${key}${mode[0].toUpperCase()}${mode.slice(1)}`];
        const v = override || value[mode];
        if (!HEX.test(v)) continue;
        out.push(`    static let ${swiftName(brand, key, mode)} = ${swiftColor(v)}`);
      }
    }
    for (const [key, value] of Object.entries(ios)) {
      if (typeof value !== "object") continue;
      if (value.hsb) {
        const [hue, sat, bri] = value.hsb;
        out.push(`    static let ${brand}${key[0].toUpperCase()}${key.slice(1)} = Color(hue: ${hue} / 360, saturation: ${sat}, brightness: ${bri})`);
        continue;
      }
      for (const mode of ["light", "dark"]) {
        if (!HEX.test(value[mode] || "")) throw new Error(`${brand}.ios.${key}.${mode} must be #rrggbb`);
        out.push(`    static let ${swiftName(brand, key, mode)} = ${swiftColor(value[mode])}`);
      }
    }
  }
  out.push("}", "");
  return out.join("\n");
}

function replaceCssBlock(text, file, brands) {
  const re = /\/\* brand:start[\s\S]*?\/\* brand:end \*\//;
  if (!re.test(text)) throw new Error(`${file} has no /* brand:start */ ... /* brand:end */ block`);
  return text.replace(re, cssBlock(brands));
}

function replaceSkillRegions(text) {
  for (const [region, brand] of Object.entries(SKILL_REGIONS)) {
    const re = new RegExp(`(<!-- brand:${region} -->)([\\s\\S]*?)(<!-- brand:end -->)`);
    const m = text.match(re);
    if (!m) throw new Error(`${SKILL_FILE} has no <!-- brand:${region} --> region`);
    let dark = false;
    const body = m[2]
      .split("\n")
      .map((line) => {
        if (/@media|data-resolved-theme="dark"/.test(line)) dark = true;
        const v = palette[brand].accent[dark ? "dark" : "light"];
        return line.replace(/^(\s*--(?:accent|ok): )#[0-9a-fA-F]{3,8};/, `$1${v};`);
      })
      .join("\n");
    text = text.replace(re, `$1${body}$3`);
  }
  return text;
}

const outputs = [];
for (const { file, brands } of CSS_TARGETS) {
  const abs = join(ROOT, file);
  // The open-source mirror ships without the personal one-off sites.
  if (!existsSync(abs)) continue;
  const before = readFileSync(abs, "utf8");
  outputs.push([file, before, replaceCssBlock(before, file, brands)]);
}
{
  const abs = join(ROOT, SWIFT_FILE);
  let before = "";
  try {
    before = readFileSync(abs, "utf8");
  } catch {}
  outputs.push([SWIFT_FILE, before, swiftFile()]);
}
{
  const before = readFileSync(join(ROOT, SKILL_FILE), "utf8");
  outputs.push([SKILL_FILE, before, replaceSkillRegions(before)]);
}

let stale = 0;
for (const [file, before, after] of outputs) {
  if (before === after) continue;
  stale++;
  if (CHECK) console.log(`stale: ${file}`);
  else {
    writeFileSync(join(ROOT, file), after);
    console.log(`wrote ${file}`);
  }
}
if (!stale) console.log("brand: everything up to date");
if (CHECK && stale) process.exit(1);
